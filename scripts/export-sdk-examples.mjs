import { readFile, mkdir, writeFile } from "node:fs/promises";
import { OrderType } from "@orbs-network/spot-ui";
import { formatAdvancedOrdersSdkFlow, formatSpotSwapSdkFlow } from "../features/developer-tools/snippets/sdk-flow-examples.ts";

// Generation only: importing the formatters never connects a wallet or calls the SDK.
const header = "// Generated by yarn examples:generate. Edit sdk-flow-examples.ts, then regenerate.\n// Read README.md and AGENTS.md in this directory before adapting this browser example.\n";
const examples = {
  "spot-swap.ts": formatSpotSwapSdkFlow({ chainId: 137, partner: "external" }),
  "advanced-orders.ts": formatAdvancedOrdersSdkFlow({ formParams: {
    orderType: OrderType.TWAP,
    inputTokenDecimals: 18,
    outputTokenDecimals: 6,
    quotedOutputAmountRaw: "4000000000",
    inputAmountUsd: "4000",
    inputTokenUsdPrice: "2000",
    outputTokenUsdPrice: "1",
    minTradeSizeUsd: 10,
    priceProtectionPercent: 3,
    userInput: { inputAmountUi: "2", isMarketOrder: true, tradeCount: 3 },
  } }),
};
const check = process.argv.includes("--check");
if (process.argv.slice(2).some(arg => arg !== "--check")) throw new Error("Usage: yarn examples:generate [--check]");
const directory = new URL("../examples/spot/", import.meta.url);
if (!check) await mkdir(directory, { recursive: true });
for (const [name, source] of Object.entries(examples)) {
  const file = new URL(name, directory);
  const code = header + source;
  if (check) {
    const current = await readFile(file, "utf8").catch(error => {
      if (error.code === "ENOENT") return undefined;
      throw error;
    });
    if (current !== code) throw new Error(`${name} is missing or stale. Run yarn examples:generate.`);
  } else {
    await writeFile(file, code);
  }
}
console.log(check ? "Standalone examples match the playground downloads." : "Updated examples/spot/*.ts.");
